#!/usr/bin/env python3
"""Generates tests/null_gl_defaults.inc from third_party/khronos/GL/glcorearb.h.

The unit tests run the menus, the renderer and the scenes on a null OpenGL (tests/null_gl.cpp):
gl46::load() receives a function for every entry point that src/gl/gl46.cpp loads (the same
selection as tools/gen_gl_loader.py). This file holds the default one of each: it does nothing,
returns zero (GL_NO_ERROR, GL_FALSE, a null pointer), and a query writes zero to the first value
of each of its outputs. tests/null_gl.cpp replaces the few whose results the game reads (object
names, compile and link status, the limits, mapped buffers, fences, read-backs).
Run from the repository root:  python3 tools/gen_null_gl.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party/khronos/GL/glcorearb.h")
OUT = os.path.join(ROOT, "tests/null_gl_defaults.inc")
EXTRA_EXT = {"GL_EXT_texture_filter_anisotropic"}   # as tools/gen_gl_loader.py
# The outputs a default query zeroes: plain values (not void*, which has no element size).
VALUE_TYPES = {"GLint", "GLuint", "GLfloat", "GLdouble", "GLboolean", "GLint64", "GLuint64", "GLsizei",
               "GLenum", "GLbitfield"}

with open(SRC, encoding="utf-8") as src:
    lines = src.read().splitlines()
block = None
funcs = []   # (name, return type, parameter text)
seen = set()
for line in lines:
    m = re.match(r"#ifndef (GL_(VERSION_\d_\d|[A-Z]+_\w+))$", line)
    if m:
        block = m.group(1)
        continue
    m = re.match(r"GLAPI (.*?)APIENTRY (gl\w+) \((.*)\);$", line)
    if m and block and (block.startswith("GL_VERSION_") or block in EXTRA_EXT) and m.group(2) not in seen:
        seen.add(m.group(2))
        funcs.append((m.group(2), m.group(1).strip(), m.group(3).strip()))


def params(text):
    """[(type, name)] of a prototype's parameter list ("void" = none)."""
    if text == "void":
        return []
    out = []
    for p in text.split(","):
        p = p.strip()
        m = re.match(r"(.*?)(\w+)$", p)
        out.append((m.group(1).strip(), m.group(2)))
    return out


out = ["// Generated by tools/gen_null_gl.py -- do not edit.",
       "// The default function of every entry point gl46::load() resolves (tests/null_gl.cpp).",
       ""]
for name, ret, text in funcs:
    body = []
    ps = params(text)
    for ptype, pname in ps:
        t = ptype.replace(" ", "")
        if t.startswith("const") or not t.endswith("*") or t.count("*") != 1:
            continue
        base = t[:-1]
        if base in VALUE_TYPES:
            body.append(f"if ({pname}) *{pname} = 0;")
        elif base == "GLchar":
            size = next((n for ty, n in ps if n in ("bufSize", "bufsize", "maxLength")), None)
            if size:
                body.append(f"if ({pname} && {size} > 0) *{pname} = 0;")
    if ret != "void":
        body.append("return {};")
    sig = ", ".join(f"{t} {n}" if not t.endswith("*") else f"{t}{n}" for t, n in ps) or "void"
    out.append(f"static {ret} APIENTRY nullgl_{name}({sig}) {{ {' '.join(body)} }}".replace("{  }", "{}"))
out += ["", "static const NullGlEntry kNullGlDefaults[] = {"]
for name, _, _ in funcs:
    out.append(f"    {{\"{name}\", reinterpret_cast<void*>(&nullgl_{name})}},")
out += ["};", ""]
with open(OUT, "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(out))
print(len(funcs), "entry points")
