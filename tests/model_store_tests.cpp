// One loopback server playing both hosts:
//   /csukuangfj2/repo/resolve/main/<name>  small files: 200; large ones: 302 to /xet/<sha256>?...
//   /old/repo/resolve/main/<name>          307 to the line above (a renamed repository), relative
//   /xet/<sha256>?X-Amz-Signature=...      the file, honouring Range (the CDN)
//   /gh/releases/download/tts-models/<archive>  302 to /gh-assets/<archive>?sig=..., the archive
struct FakeHosts {
    std::mutex mu;
    std::set<std::string> corrupt, cut, insecure, missing;   // per file name, on the hub
    std::set<std::string> cutDone;
    bool cutEvery = false;   // cut every transfer of a 'cut' file, not only the first
    bool archiveMissing = false;
    int pieceDelayMs = 0;
    std::string archive = blob(kFakeArchive, sizeof(kFakeArchive));
    fakehttp::Server srv;

    FakeHosts() : srv([this](const fakehttp::Request& r) { return answer(r); }) {}

    fakehttp::Reply answer(const fakehttp::Request& r) {
        std::lock_guard<std::mutex> lk(mu);
        fakehttp::Reply rep;
        const std::string hub = "/csukuangfj2/repo/resolve/main/", old = "/old/repo/resolve/main/";
        if (r.path.compare(0, old.size(), old) == 0) {
            rep.status = 307;
            rep.headers.emplace_back("Location", hub + r.path.substr(old.size()));
            return rep;
        }
        if (r.path.compare(0, hub.size(), hub) == 0) {
            std::string name = r.path.substr(hub.size());
            int i = index(name);
            if (i < 0 || missing.count(name)) {
                rep.status = 404;
                rep.body = "Entry not found";
                return rep;
            }
            rep.headers.emplace_back("X-Repo-Commit", "0123456789abcdef0123456789abcdef01234567");
            if (insecure.count(name)) {
                rep.status = 302;
                rep.headers.emplace_back("Location", "http://example.com/" + name);
                return rep;
            }
            if (kSizes[i] < 2000) {   // a regular git file: answered by the resolve endpoint itself
                rep = fakehttp::fileReply(content(i, name), r);
                rep.headers.emplace_back("ETag", "\"git-blob\"");
                return rep;
            }
            rep.status = 302;   // an LFS/Xet file: to the CDN with a signed URL
            rep.headers.emplace_back("Location", "http://127.0.0.1:" + std::to_string(srv.port()) + "/xet/" + kHashes[i] +
                                                     "?X-Amz-Signature=abc&X-Amz-Expires=3600");
            rep.headers.emplace_back("X-Linked-Size", std::to_string(kSizes[i]));
            rep.headers.emplace_back("X-Linked-Etag", std::string("\"") + kHashes[i] + "\"");
            return rep;
        }
        if (r.path.compare(0, 5, "/xet/") == 0) {
            std::string sha = r.path.substr(5, 64);
            for (int i = 0; i < 9; ++i) {
                if (sha != kHashes[i]) continue;
                rep = fakehttp::fileReply(content(i, kNames[i]), r);
                rep.pieceDelayMs = pieceDelayMs;
                if (cut.count(kNames[i]) && (cutEvery || !cutDone.count(kNames[i]))) {
                    cutDone.insert(kNames[i]);
                    rep.cutAfter = rep.body.size() / 3;
                }
                return rep;
            }
            rep.status = 404;
            return rep;
        }
        std::string asset = std::string("/gh/releases/download/tts-models/") + kFolder + ".tar.bz2";
        if (r.path == asset && !archiveMissing) {
            rep.status = 302;
            rep.headers.emplace_back("Location", "http://localhost:" + std::to_string(srv.port()) + "/gh-assets/" + kFolder +
                                                     ".tar.bz2?sig=1");
            return rep;
        }
        if (r.path.compare(0, 11, "/gh-assets/") == 0 && !archiveMissing) {
            rep = fakehttp::fileReply(archive, r);
            rep.pieceDelayMs = pieceDelayMs;
            return rep;
        }
        rep.status = 404;
        return rep;
    }
    static int index(const std::string& name) {
        for (int i = 0; i < 9; ++i)
            if (name == kNames[i]) return i;
        return -1;
    }
    std::string content(int i, const std::string& name) {
        std::string c = fakeContent(i);
        if (corrupt.count(name)) c[c.size() / 2] ^= 0x40;
        return c;
    }
    int requests(const std::string& prefix) {
        int n = 0;
        for (const fakehttp::Request& q : srv.requests()) n += q.path.compare(0, prefix.size(), prefix) == 0;
        return n;
    }

    tts::ModelManifest manifest(bool renamedRepo = false) {
        tts::ModelManifest m;
        for (int i = 0; i < 9; ++i) m.files.push_back({kNames[i], kSizes[i], kHashes[i]});
        m.hubBase = srv.url(renamedRepo ? "/old/repo/resolve/main/" : "/csukuangfj2/repo/resolve/main/");
        m.hubLabel = "127.0.0.1/csukuangfj2/repo";
        m.archiveUrl = srv.url(std::string("/gh/releases/download/tts-models/") + kFolder + ".tar.bz2");
        m.archiveLabel = "127.0.0.1 (release archive)";
        m.archiveSize = sizeof(kFakeArchive);
        m.archiveSha256 = kArchiveSha;
        m.archiveFolder = kFolder;
        return m;
    }
};

struct JobRun {
    tts::DownloadProgress last;
    std::set<int> phases;   // those seen by polling: a fast job can pass one unseen, so only absences are checked
    std::set<std::string> labels;
    double seconds = 0;
};
tts::ModelDownloader::Options fastOptions() {
    tts::ModelDownloader::Options o;
    o.timeoutMs = 3000;
    o.retryDelayMs = 20;
    o.userAgent = "Scacelith/test";
    return o;
}
JobRun runJob(tts::ModelDownloader& d, const tts::ModelDownloader::Options& o = fastOptions(),
              const std::function<bool(const tts::DownloadProgress&)>& cancelWhen = nullptr) {
    JobRun r;
    auto t0 = std::chrono::steady_clock::now();
    CHECK(d.start(o));
    CHECK(!d.start(o));   // one job at a time
    while (d.running()) {
        tts::DownloadProgress p = d.progress();
        r.phases.insert(int(p.phase));
        if (!p.sourceLabel.empty()) r.labels.insert(p.sourceLabel);
        if (cancelWhen && cancelWhen(p)) d.cancel();
        std::this_thread::sleep_for(std::chrono::milliseconds(1));
    }
    d.wait();
    r.last = d.progress();
    r.phases.insert(int(r.last.phase));
    r.seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    return r;
}
bool allGood(const TempFolder& t) {
    for (int i = 0; i < 9; ++i)
        if (slurp(t.dir + kNames[i]) != fakeContent(i)) return false;
    return true;
}
