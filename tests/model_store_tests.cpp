// The real thing, once, by hand (needs the network, not run by default):
//   SCACELITH_NET_TESTS=1 ./scacelith_tests model_store_real_github
// downloads the release archive from GitHub into a temporary folder (no hub: the fallback path),
// extracts and checks the nine files. SCACELITH_NET_TESTS=hub tries Hugging Face first.
TEST(model_store_real_github) {
    const char* env = std::getenv("SCACELITH_NET_TESTS");
    if (!env || !*env) SKIP("SCACELITH_NET_TESTS not set");
    TempFolder t("real");
    tts::ModelDownloader d(tts::supertonicManifest(), t.dir);
    tts::ModelDownloader::Options o;
    o.useHub = std::string(env) == "hub";
    auto t0 = std::chrono::steady_clock::now();
    double archiveAt = 0, extractAt = 0, verifyAt = 0;
    CHECK(d.start(o));
    Phase last = Phase::Idle;
    while (d.running()) {
        tts::DownloadProgress p = d.progress();
        double s = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
        if (p.phase != last) {
            if (p.phase == Phase::Archive) archiveAt = s;
            if (p.phase == Phase::Extracting) extractAt = s;
            if (p.phase == Phase::Verifying) verifyAt = s;
            std::fprintf(stderr, "  %6.1f s: phase %d %s\n", s, int(p.phase), p.sourceLabel.c_str());
            last = p.phase;
        }
        std::this_thread::sleep_for(std::chrono::milliseconds(20));
    }
    d.wait();
    tts::DownloadProgress p = d.progress();
    double end = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    std::fprintf(stderr, "  result: phase %d error '%s' %s; hub error '%s'\n", int(p.phase), p.error.c_str(), p.detail.c_str(),
                 p.hubError.c_str());
    std::fprintf(stderr, "  timings: download %.1f s, extraction %.1f s, verification %.1f s, total %.1f s\n",
                 extractAt - archiveAt, verifyAt - extractAt, end - verifyAt, end);
    CHECK_EQ(int(p.phase), int(Phase::Done));
    CHECK_EQ(int(tts::verifyModel(tts::supertonicManifest(), t.dir)), int(tts::ModelStatus::Ready));
}

// The decoder on the real archive, offline, when a local copy is given:
//   SCACELITH_SUPERTONIC_ARCHIVE=/path/to/sherpa-onnx-supertonic-3-tts-int8-2026-05-11.tar.bz2
TEST(model_store_real_archive) {
    const char* archive = std::getenv("SCACELITH_SUPERTONIC_ARCHIVE");
    if (!archive || !net::sys::fileExists(archive)) SKIP("SCACELITH_SUPERTONIC_ARCHIVE not set");
    TempFolder t("realarchive");
    const tts::ModelManifest& m = tts::supertonicManifest();
    std::vector<std::string> names;
    for (const tts::ManifestFile& f : m.files) names.push_back(f.name);
    std::string error;
    auto t0 = std::chrono::steady_clock::now();
    CHECK(tts::extractModelArchive(m, archive, t.dir, names, error));
    double s = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    std::fprintf(stderr, "  extracted and checked 9 files (%.1f MB) in %.2f s: %.1f MB/s of output\n", m.totalBytes() / 1e6, s,
                 m.totalBytes() / 1e6 / s);
    CHECK_EQ(error, std::string(""));
    CHECK_EQ(int(tts::verifyModel(m, t.dir)), int(tts::ModelStatus::Ready));
}
