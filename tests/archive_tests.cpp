TEST(bzip2_vectors) {
    struct Case {
        const char* name;
        std::string compressed, expected;
    } cases[] = {
        {"empty", BLOB(kEmpty), std::string()},
        {"hello", BLOB(kHello), "hello, bzip2\n"},
        {"runs", BLOB(kRuns), runsInput()},
        {"multiblock", BLOB(kMultiblock), multiblockInput()},
        {"concatenated", BLOB(kConcatenated), "first stream, second stream"},
    };
    CHECK_EQ(sha(runsInput()), std::string("9a161affbb25e3486930e4cb38e38ec3ece284b1d6bac2e60ff38c64244f5ab0"));
    CHECK_EQ(sha(multiblockInput()), std::string("34bfd04786afe0611e0a356547523dad6e47ba9ca510d5ec4edcdecf0c146842"));
    for (const Case& c : cases) {
        std::string out, error;
        bool ok = bz2::decompress(c.compressed, out, &error);
        if (!ok || out != c.expected) std::fprintf(stderr, "  %s: %s, %zu bytes\n", c.name, error.c_str(), out.size());
        CHECK(ok);
        CHECK(out == c.expected);
        // Cut differently: one byte in at a time, odd output sizes.
        for (size_t inStep : {size_t(1), size_t(7), size_t(4096)}) {
            for (size_t outStep : {size_t(1), size_t(13), size_t(65536)}) {
                if (c.expected.size() > 10000 && (inStep == 1 || outStep == 1)) continue;   // slow and nothing new
                CHECK(decodeStepwise(c.compressed, inStep, outStep, out, error));
                CHECK(out == c.expected);
            }
        }
    }
}

TEST(bzip2_corrupt_streams_fail_cleanly) {
    std::string out, error;
    // Not bzip2 at all, empty, truncated anywhere.
    CHECK(!bz2::decompress("", out, &error));
    CHECK(!error.empty());
    CHECK(!bz2::decompress("BZh0", out, &error));
    CHECK(!bz2::decompress("PK\x03\x04 zip", out, &error));
    const std::string good = BLOB(kRuns);
    for (size_t cut = 1; cut < good.size(); cut += 37) {
        error.clear();
        CHECK(!bz2::decompress(good.substr(0, cut), out, &error));
        CHECK(!error.empty());
    }
    // Trailing garbage after the end of the stream.
    CHECK(!bz2::decompress(good + "garbage", out, &error));
    // One bit flipped anywhere: always an error (header, tables, symbols or a CRC), never a crash
    // or a hang, never wrong data reported as good.
    const std::string multi = BLOB(kMultiblock);
    int failures = 0, total = 0;
    for (const std::string* s : {&good, &multi}) {
        for (size_t i = 0; i < s->size(); i += (s->size() > 2000 ? 11 : 3)) {
            std::string bad = *s;
            bad[i] = char(bad[i] ^ (1 << (i % 8)));
            ++total;
            if (!bz2::decompress(bad, out, &error)) ++failures;
            else CHECK(out == (s == &good ? runsInput() : multiblockInput()));   // a flip in unused padding bits
        }
    }
    CHECK(failures >= total - 2);
    // A CRC mismatch is reported as such.
    std::string badCrc = BLOB(kHello);
    badCrc[10] ^= 0x01;   // inside the block CRC (bytes 10..13)
    CHECK(!bz2::decompress(badCrc, out, &error));
    CHECK(error.find("CRC") != std::string::npos);
}

TEST(tar_reader_formats) {
    TarBuilder t;
    t.header("dir/", '5', 0);
    t.file("dir/a.txt", "alpha");
    t.header("b.bin", '0', 600, "a/deep/prefix");   // ustar prefix + name
    t.body(std::string(600, 'b'));
    std::string longName = "dir/" + std::string(150, 'n') + ".onnx";
    t.file("././@LongLink", longName + std::string(1, '\0'), 'L');   // GNU long name, then its entry
    t.file(longName.substr(0, 100), "long");
    std::string pax = "path=dir/pax-name.json\n";
    std::string rec = std::to_string(pax.size() + 3) + " " + pax;   // "26 path=...\n": length counts itself
    t.file("PaxHeader", rec, 'x');
    t.file("ignored-name", "pax");
    t.header("dir/link", '2', 0, "", "a.txt");
    t.file("dir/empty", "");
    t.end();
    TarRead r = readTar(t.data);
    CHECK_EQ(r.error, std::string(""));
    CHECK_EQ(r.entries.size(), size_t(7));
    if (r.entries.size() == 7) {
        CHECK(r.entries[0].path == "dir/" && r.entries[0].type == '5' && !r.entries[0].regular());
        CHECK(r.entries[1].path == "dir/a.txt" && r.entries[1].regular() && r.contents[1] == "alpha");
        CHECK(r.entries[2].path == "a/deep/prefix/b.bin" && r.contents[2] == std::string(600, 'b'));
        CHECK(r.entries[3].path == longName && r.contents[3] == "long");
        CHECK(r.entries[4].path == "dir/pax-name.json" && r.contents[4] == "pax");
        CHECK(r.entries[5].type == '2' && !r.entries[5].regular() && r.entries[5].linkTarget == "a.txt");
        CHECK(r.entries[6].path == "dir/empty" && r.entries[6].size == 0 && r.contents[6].empty());
    }
    // Data not read is skipped by next().
    TarRead partial = readTar(t.data, 2, 1);
    CHECK_EQ(partial.entries.size(), size_t(7));
    if (partial.entries.size() == 7) CHECK(partial.contents[2] == "bb" && partial.contents[4] == "pa");
    // Without the closing zero blocks: ends at the last entry.
    TarBuilder open;
    open.file("x", "y");
    CHECK_EQ(readTar(open.data).entries.size(), size_t(1));
    CHECK_EQ(readTar(open.data).error, std::string(""));
}

