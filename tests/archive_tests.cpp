std::string blob(const uint8_t* p, size_t n) { return std::string(reinterpret_cast<const char*>(p), n); }
#define BLOB(a) blob(a, sizeof(a))

// Decodes through a source that hands out at most 'inStep' bytes at a time, into reads of at
// most 'outStep' bytes: the state machine must not depend on how the data is cut.
bool decodeStepwise(const std::string& in, size_t inStep, size_t outStep, std::string& out, std::string& error) {
    size_t at = 0;
    bz2::Decoder d([&](uint8_t* buf, size_t n) {
        size_t k = std::min({n, inStep, in.size() - at});
        std::memcpy(buf, in.data() + at, k);
        at += k;
        return long(k);
    });
    out.clear();
    std::vector<uint8_t> buf(outStep);
    for (;;) {
        long r = d.read(buf.data(), buf.size());
        if (r < 0) {
            error = d.error();
            return false;
        }
        if (r == 0) return true;
        out.append(reinterpret_cast<char*>(buf.data()), size_t(r));
    }
}

// ---- A tar writer for the reader's tests ----
struct TarBuilder {
    std::string data;
    static void octal(char* f, size_t len, uint64_t v) {
        std::string s(len - 1, '0');
        for (size_t i = len - 1; i-- > 0 && v; v >>= 3) s[i] = char('0' + (v & 7));
        std::memcpy(f, s.data(), len - 1);
        f[len - 1] = 0;
    }
    void header(const std::string& name, char type, uint64_t size, const std::string& prefix = "", const std::string& link = "",
                bool corruptSum = false) {
        char h[512] = {};
        std::memcpy(h, name.data(), std::min<size_t>(name.size(), 100));
        octal(h + 100, 8, 0644);
        octal(h + 108, 8, 1000);
        octal(h + 116, 8, 1000);
        octal(h + 124, 12, size);
        octal(h + 136, 12, 1778636220);
        h[156] = type;
        std::memcpy(h + 157, link.data(), std::min<size_t>(link.size(), 100));
        std::memcpy(h + 257, "ustar\0" "00", 8);
        std::memcpy(h + 345, prefix.data(), std::min<size_t>(prefix.size(), 155));
        std::memset(h + 148, ' ', 8);
        unsigned sum = 0;
        for (unsigned char c : h) sum += c;
        if (corruptSum) ++sum;
        octal(h + 148, 7, sum);
        h[155] = ' ';
        data.append(h, 512);
    }
    void body(const std::string& b) {
        data += b;
        data.append((512 - b.size() % 512) % 512, '\0');
    }
    void file(const std::string& name, const std::string& b, char type = '0') {
        header(name, type, b.size());
        body(b);
    }
    void end() { data.append(1024, '\0'); }
};

struct TarRead {
    std::vector<tar::Entry> entries;
    std::vector<std::string> contents;
    std::string error;
};
// Reads every entry; 'readUpTo' bytes of each entry's data (the rest is skipped by next()).
TarRead readTar(const std::string& data, size_t readUpTo = SIZE_MAX, size_t step = 777) {
    size_t at = 0;
    tar::Reader r([&](uint8_t* buf, size_t n) {
        size_t k = std::min({n, step, data.size() - at});
        std::memcpy(buf, data.data() + at, k);
        at += k;
        return long(k);
    });
    TarRead out;
    tar::Entry e;
    while (r.next(e)) {
        out.entries.push_back(e);
        std::string c;
        uint8_t buf[300];
        long n;
        while (c.size() < readUpTo && (n = r.read(buf, std::min<size_t>(sizeof buf, readUpTo - c.size()))) > 0)
            c.append(reinterpret_cast<char*>(buf), size_t(n));
        out.contents.push_back(c);
    }
    out.error = r.error();
    return out;
}

